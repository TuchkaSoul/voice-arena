"""Числа на входе TTS: смысл, падежи и границы токенов."""
import pytest

from synth.text import normalize


@pytest.mark.parametrize("source, expected", [
    ("Задержка 3,5 секунды.", "Задержка три целых пять десятых секунды."),
    ("Масса 1.25 кг.", "Масса одна целая двадцать пять сотых килограмма."),
    ("Расстояние 2,01 км.", "Расстояние две целых одна сотая километра."),
    ("Погрешность 0,05%.", "Погрешность ноль целых пять сотых процента."),
    ("Цена 21,50 руб.", "Цена двадцать одна целая пятьдесят сотых рубля"),
    ("0,001", "ноль целых одна тысячная"),
    ("1.000001", "одна целая одна миллионная"),
    ("0,000000001", "ноль целых одна миллиардная"),
    ("0,0", "ноль целых ноль десятых"),
    ("3,00", "три целых ноль сотых"),
    ("4 250,75 рублей", "четыре тысячи двести пятьдесят целых семьдесят пять сотых рубля"),
    ("1,21 минуты", "одна целая двадцать одна сотая минуты"),
    ("1,11 секунд", "одна целая одиннадцать сотых секунды"),
    ("1,5 коп.", "одна целая пять десятых копейки"),
])
def test_decimal_precision_and_unit_case(source, expected):
    assert normalize(source) == expected


@pytest.mark.parametrize("source, expected", [
    ("Начало в 14:30.", "Начало в четырнадцать часов тридцать минут."),
    ("Встреча в 09:01.", "Встреча в девять часов одну минуту."),
    ("В 21:21:01.", "В двадцать один час двадцать одну минуту одну секунду."),
    ("00:00", "ноль часов ноль минут"),
    ("23:59:59", "двадцать три часа пятьдесят девять минут пятьдесят девять секунд"),
    ("01:01", "один час одна минута"),
    ("с 09:05 до 18:30", "с девяти часов пяти минут до восемнадцати часов тридцати минут"),
    ("после 21:01", "после двадцати одного часа одной минуты"),
    ("От 11:11", "От одиннадцати часов одиннадцати минут"),
])
def test_clock_formats_and_prepositions(source, expected):
    assert normalize(source) == expected


@pytest.mark.parametrize("source", ["24:00", "12:60", "23:59:60", "99:01"])
def test_invalid_clock_is_not_silently_pronounced(source):
    with pytest.raises(ValueError, match="время"):
        normalize(source)


@pytest.mark.parametrize("source, expected", [
    ("-10", "минус десять"),
    ("−10", "минус десять"),
    ("− 2", "минус два"),
    ("Температура: - 10 °C.", "Температура: минус десять градусов цельсия."),
    ("Температура -1 °С.", "Температура минус один градус цельсия."),
    ("-0,5 °C", "минус ноль целых пять десятых градуса цельсия"),
    ("−2.05 кг", "минус две целых пять сотых килограмма"),
    ("+2,5%", "плюс две целых пять десятых процента"),
    ("-4 250 руб.", "минус четыре тысячи двести пятьдесят рублей"),
    ("0 °C", "ноль градусов цельсия"),
    ("21 °C", "двадцать один градус цельсия"),
    ("Значения: 1,-2,-0.5", "Значения: один,минус два,минус ноль целых пять десятых"),
])
def test_signed_numbers_and_temperatures(source, expected):
    assert normalize(source) == expected


@pytest.mark.parametrize("source, expected", [
    ("к 15 марта", "к пятнадцатому марта"),
    ("К 21 сентября", "К двадцать первому сентября"),
    ("ко 2 мая", "ко второму мая"),
    ("на 3 июня", "на третье июня"),
    ("по 23 апреля", "по двадцать третье апреля"),
    ("после 15 марта", "после пятнадцатого марта"),
    ("с 1 мая", "с первого мая"),
    ("до 31 декабря", "до тридцать первого декабря"),
    ("о 23 августа", "о двадцать третьем августа"),
    ("перед 21 сентября", "перед двадцать первым сентября"),
    ("перед 3 марта", "перед третьим марта"),
    ("при 15 марта", "при пятнадцатом марта"),
    ("с 1 по 3 мая", "с первого по третье мая"),
    ("со 2 до 15 марта", "со второго до пятнадцатого марта"),
    ("с 1 мая по 3 мая", "с первого мая по третье мая"),
    ("к утру 15 марта", "к утру пятнадцатого марта"),
    ("29 февраля", "двадцать девятого февраля"),
])
def test_calendar_day_cases_and_ranges(source, expected):
    assert normalize(source) == expected


@pytest.mark.parametrize("source", ["0 марта", "32 мая", "31 апреля", "30 февраля", "с 31 по 32 марта"])
def test_invalid_day_is_reported(source):
    with pytest.raises(ValueError, match="дата"):
        normalize(source)


@pytest.mark.parametrize("source, expected", [
    ("5-10", "пять-десять"),
    ("5 - 10", "пять - десять"),
    ("5–10", "пять - десять"),
    ("Срок — 10 дней", "Срок - десять дней"),
    ("Тест-2", "Тест-два"),
    ("Счёт 1:2", "Счёт один:два"),
    ("Версия 1.2.3", "Версия один.два.три"),
    ("1, 2 и 3", "один, два и три"),
])
def test_punctuation_ranges_and_versions_are_not_signs_or_decimals(source, expected):
    assert normalize(source) == expected


def test_number_expansion_can_be_disabled():
    source = "-3,5 кг в 14:30 к 15 марта"
    assert normalize(source, expand_numbers=False) == source


def test_abbreviation_expansion_is_independent():
    assert normalize("-3,5 кг", expand_abbrev=False) == "минус три целых пять десятых килограмма"


def test_stress_is_preserved_with_numeric_expansion():
    assert normalize("з+амок к 15 марта", strip_stress=False) == "з+амок к пятнадцатому марта"


def test_decimal_precision_limit_is_reported():
    with pytest.raises(ValueError, match="девяти"):
        normalize("0,0000000001")


def test_result_is_idempotent():
    text = normalize("К 15 марта в 09:01 принесите 3,5 кг, температура -10 °C.")
    assert normalize(text) == text
